// Get tour image by ID
export const getTourImage = (tourName) => {
  const normalized = tourName.toLowerCase().replace(/\s+/g, '');

  const tourMap = {
    'greatoceanroad': tourImages.greatOceanRoad,
    'penguinparade': tourImages.penguinParade,
    'yarravalley': tourImages.yarraValley,
    'melbournecity': tourImages.melbourneCity,
    'grampians': tourImages.grampians,
    'healesville': tourImages.healesville,
    'dandenong': tourImages.dandenong,
    'mornington': tourImages.mornington,
  };

  return tourMap[normalized] || tourImages.greatOceanRoad;
};

// Image fallback for errors
export const imageWithFallback = (imageUrl, fallbackUrl = tourImages.greatOceanRoad.card) => {
  return {
    onError: (e) => {
      e.target.src = fallbackUrl;
    }
  };
};
